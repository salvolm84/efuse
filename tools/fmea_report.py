"""Write the FMEA effects report of every fault-injection bench that has an
FMEA table: docs/fmea/<bench>.md, from the simulation results.

    python3 tools/fmea_report.py                             # from the .log files
    python3 tools/fmea_report.py --json docs/results.json    # from stored results (CI)

See tools/fmea.py for the table format.
"""
import argparse
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fmea  # noqa: E402
import validate  # noqa: E402


def fmt_t(s):
    if math.isnan(s):
        return "–"
    return f"{s * 1e6:.1f} µs" if s < 1e-3 else f"{s * 1e3:.2f} ms"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--json", help="read the results from this JSON file instead of the .log files")
    a = ap.parse_args()
    results = validate.load_json(a.json) if a.json else validate.load_logs()
    for bench, path in fmea.tables().items():
        r = results.get(f"testbenches/{bench}", {})

        def res(key, k, r=r):
            v = r.get(key.lower(), [])
            return v[k] if len(v) > k and v[k] is not None else float("nan")
        lines = [f"# FMEA simulation: {bench}", "",
                 f"Generated by `tools/fmea_report.py` from the results of "
                 f"[`testbenches/{bench}.cir`](../../testbenches/{bench}.cir) and the table "
                 f"[`{bench}.csv`](./{bench}.csv). Detection times are measured from the fault "
                 f"onset ({fmea.fault_onset(bench) * 1e3:g} ms); \"–\" = no reaction.", "",
                 "| FID | Item | Failure mode | S | Expected detection | DIAG1 | DIAG2 | FLTB | PG | Expected effect / safe state | Criteria | Result |",
                 "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        n_pass = 0
        rows = fmea.rows(path)
        for row in rows:
            checks, det = fmea.evaluate(res, bench, row)
            ok = all(not math.isnan(v) and lo <= v <= hi for _, v, lo, hi, _, _ in checks)
            n_pass += ok
            crit = "; ".join(c.strip() for c in row["Criteria"].split(";") if c.strip())
            lines.append(
                f"| {row['FID']} | {row['Item']} | {row['Failure mode']} | {row['S']} | {row['Expected detection']}"
                f"{' ≤ ' + row['Max detection time [ms]'] + ' ms' if row['Max detection time [ms]'] else ''} | "
                + " | ".join(fmt_t(det[mch]) for mch in fmea.MECHS)
                + f" | {row['Expected effect']}; {row['Expected safe state']} | `{crit}` | {'PASS' if ok else '**FAIL**'} |")
        lines[3:3] = [f"**{n_pass} / {len(rows)} rows as expected.**", ""]
        out = os.path.join(fmea.FMEA_DIR, bench + ".md")
        with open(out, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        print(f"{out}: {n_pass}/{len(rows)} rows as expected")


if __name__ == "__main__":
    main()
